import { expect, test } from '@playwright/test'

test('guest shopping flow, sharing, keyboard access and durable offline edits', async ({ page, context, browser }) => {
    await page.goto('/')
    await expect(page.getByRole('heading', { level: 1 })).toContainText('shopping lists')
    await page.getByRole('link', { name: 'Create Free List' }).click()
    await page.getByRole('textbox', { name: 'List name' }).fill('Offline grocery run')
    await page.getByRole('button', { name: 'Create list' }).click()
    await expect(page.getByRole('heading', { name: 'Offline grocery run' })).toBeVisible()
    const field = page.getByRole('combobox', { name: 'Item name' })
    await field.fill('Rice')
    await field.press('Enter')
    await expect(page.getByRole('checkbox', { name: 'Complete Rice' })).toBeVisible()
    await expect(page.getByRole('status').filter({ hasText: 'Available offline' })).toBeVisible({ timeout: 15000 })

    await page.getByRole('button', { name: 'Share' }).click()
    await page.getByLabel('Invitation permission').selectOption('complete')
    await page.getByRole('button', { name: 'Create invitation link' }).click()
    const link = page.getByRole('textbox', { name: 'Invitation link' })
    await expect(link).toHaveValue(/\/join#[a-f0-9]{64}$/)
    await page.getByRole('button', { name: 'QR code' }).click()
    await expect(page.getByRole('img', { name: 'QR code for this invitation' })).toBeVisible()
    const recipient = await browser.newContext()
    const other = await recipient.newPage()
    await other.goto(await link.inputValue())
    await other.getByRole('textbox', { name: /Your display name/ }).fill('Sam')
    await other.getByRole('button', { name: 'Open list' }).click()
    await expect(other.getByRole('checkbox', { name: 'Complete Rice' })).toBeVisible()
    await expect(other.getByRole('button', { name: 'Add item' })).toHaveCount(0)
    await expect(other.getByRole('status').filter({ hasText: 'Available offline' })).toBeVisible({ timeout: 15000 })
    await recipient.close()

    await page.getByRole('button', { name: 'Share' }).click()
    await page.getByRole('button', { name: 'Details for Rice' }).click()
    await expect(page.getByRole('dialog')).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await context.setOffline(true)
    await field.fill('Oat milk')
    await field.press('Enter')
    await expect(page.getByRole('checkbox', { name: 'Complete Oat milk' })).toBeVisible()
    await page.getByRole('checkbox', { name: 'Complete Rice' }).focus()
    await page.keyboard.press('Space')
    await expect(page.getByRole('checkbox', { name: 'Restore Rice' })).toBeChecked()
    await page.reload()
    await expect(page.getByRole('checkbox', { name: 'Restore Rice' })).toBeChecked()
    await expect(page.getByRole('checkbox', { name: 'Complete Oat milk' })).toBeVisible()
    await expect(page.getByText('Offline · 2 unsynced')).toBeVisible()
    await context.setOffline(false)
    await expect(page.getByRole('status').filter({ hasText: 'Available offline' })).toBeVisible({ timeout: 20000 })
    await page.reload()
    await expect(page.getByRole('checkbox', { name: 'Restore Rice' })).toBeChecked()
    await expect(page.getByRole('checkbox', { name: 'Complete Oat milk' })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(await page.evaluate(() => innerWidth))
})

test('downloads photos and keeps shopping mode usable offline', async ({ page, browser }) => {
    await page.goto('/create')
    await page.getByRole('button', { name: 'Create list' }).click()
    const field = page.getByRole('combobox', { name: 'Item name' })
    await field.fill('Bread')
    await field.press('Enter')
    await expect(page.getByRole('status').filter({ hasText: 'Available offline' })).toBeVisible({ timeout: 15000 })
    await page.getByRole('button', { name: 'Details for Bread' }).click()
    await page.getByText('Product photo', { exact: true }).click()
    await page.locator('input[type=file]').setInputFiles('public/icons/icon-192.png')
    await page.getByRole('button', { name: 'Upload photo' }).click()
    await expect(page.locator('.item-photo')).toHaveCount(1)
    await page.getByRole('button', { name: 'Close', exact: true }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Available offline' })).toBeVisible({ timeout: 15000 })

    await page.getByRole('button', { name: 'Share' }).click()
    await page.getByRole('button', { name: 'Create invitation link' }).click()
    const link = page.getByRole('textbox', { name: 'Invitation link' })
    await expect(link).toHaveValue(/\/join#[a-f0-9]{64}$/)
    const recipient = await browser.newContext()
    try {
        const other = await recipient.newPage()
        await other.goto(await link.inputValue())
        await other.getByRole('button', { name: 'Open list' }).click()
        await expect(other.getByRole('status').filter({ hasText: 'Available offline' })).toBeVisible({ timeout: 15000 })
        await other.getByRole('checkbox', { name: 'Complete Bread' }).click()
        await expect(page.getByRole('checkbox', { name: 'Restore Bread' })).toBeChecked({ timeout: 16000 })

        await recipient.setOffline(true)
        await other.reload()
        await other.getByText('More', { exact: true }).click()
        await other.getByRole('button', { name: 'Shopping Mode', exact: true }).click()
        const photo = other.locator('.item-photo')
        await expect(photo).toHaveAttribute('src', /^blob:/)
        await expect.poll(() => photo.evaluate(img => img.complete && img.naturalWidth > 0)).toBe(true)
        await other.getByRole('checkbox', { name: 'Restore Bread' }).click()
        await expect(other.getByRole('checkbox', { name: 'Complete Bread' })).toBeVisible()
        await other.getByRole('button', { name: 'Exit Shopping Mode' }).click()
        await expect(other.getByRole('combobox', { name: 'Item name' })).toBeVisible()
    } finally {
        await recipient.close()
    }
})
